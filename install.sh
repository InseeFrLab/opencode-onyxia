#!/usr/bin/env bash
# Installs the OpenCode Onyxia configuration GLOBALLY (~/.config/opencode),
# so it applies to ALL projects and all services.
#
# Usage:            ./install.sh
# Models only:      ./install.sh --bare     (the Onyxia LLM gateway provider + models, the default model and
#                                            the title model; NO agents, permissions, policies, skills,
#                                            commands, prompts or AGENTS.md)
# Custom target:    OPENCODE_CONFIG_DIR=/path ./install.sh
# Claude Code too:  ./install.sh --claude   (also copies skills to ~/.claude/skills
#                                            so Claude Code picks them up; not with --bare)
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEST="${OPENCODE_CONFIG_DIR:-$HOME/.config/opencode}"

BARE=false
WITH_CLAUDE=false
for arg in "$@"; do
  case "$arg" in
    --bare) BARE=true ;;
    --claude) WITH_CLAUDE=true ;;
    *) echo "Unknown option: $arg" >&2; echo "Usage: ./install.sh [--bare] [--claude]" >&2; exit 2 ;;
  esac
done
if [ "$BARE" = true ] && [ "$WITH_CLAUDE" = true ]; then
  echo "--bare and --claude cannot be combined: --bare installs no skills for Claude Code to pick up." >&2
  exit 2
fi

# This config is in the NATIVE opencode v2 format and is not readable by v1.
if command -v opencode >/dev/null 2>&1; then
  oc_version="$(opencode --version 2>/dev/null | head -n1 || true)"
  case "$oc_version" in
    *v2.*|*" 2."*|2.*) ;;
    *) echo "⚠ opencode v2 expected, found: ${oc_version:-unknown}." >&2
       echo "  Install v2:  curl -fsSL https://opencode.ai/v2/install | bash" >&2 ;;
  esac
else
  echo "⚠ opencode not found. Install v2:  curl -fsSL https://opencode.ai/v2/install | bash" >&2
fi

# ---------------------------------------------------------------------------------------------------------------
# --bare: assemble a models-only opencode.jsonc from the marked regions of opencode.jsonc (single source of truth:
# adding a model there updates both modes). It is built and verified in a temp file BEFORE anything is touched.
# ---------------------------------------------------------------------------------------------------------------
extract_region() {  # $1 = marker name; prints the lines between `>>> NAME:begin` and `<<< NAME:end`
  sed -n "/>>> $1:begin/,/<<< $1:end/p" "$SRC/opencode.jsonc" | sed '1d;$d'
}

build_bare_config() {  # $1 = output file
  {
    echo '{'
    echo '  "$schema": "https://opencode.ai/config.json",'
    echo '  // ========================================================================='
    echo '  //  BARE CONFIG, generated by `install.sh --bare` from opencode.jsonc: the Onyxia LLM gateway'
    echo '  //  models and nothing else (no agents, permissions, policies, skills, commands or AGENTS.md).'
    echo '  //  Native opencode v2 format: not readable by opencode v1. Re-run the script to update the models.'
    echo '  //'
    extract_region bare
    echo '  "agents": {'
    extract_region bare-title
    echo '  }'
    echo '}'
  } > "$1"
  for key in '"providers"' '"onyxia"' '"model"' '"title"'; do
    if ! grep -q "$key" "$1"; then
      echo "✗ Could not build the bare config: $key not found between the bare markers of opencode.jsonc." >&2
      echo "  (the '>>> bare:begin' / '>>> bare-title:begin' marker comments must stay in opencode.jsonc)" >&2
      rm -f "$1"
      return 1
    fi
  done
}

if [ "$BARE" = true ]; then
  echo "→ Installing the BARE Onyxia config (models only) into: $DEST"
  mkdir -p "$DEST"
  tmp="$(mktemp "$DEST/.opencode.jsonc.XXXXXX")"
  trap 'rm -f "$tmp"' EXIT
  build_bare_config "$tmp" || exit 1
  chmod 644 "$tmp"

  # Back up an existing config (only the config: AGENTS.md, skills... are not touched in bare mode)
  if [ -f "$DEST/opencode.jsonc" ] || [ -f "$DEST/opencode.json" ]; then
    bak="$DEST/backup-$(date +%Y%m%d-%H%M%S)"
    echo "  Existing config detected → backing it up to $bak"
    mkdir -p "$bak"
    cp -f "$DEST"/opencode.json* "$bak/" 2>/dev/null || true
  fi
  mv -f "$tmp" "$DEST/opencode.jsonc"
  trap - EXIT

  left=""
  for item in AGENTS.md prompts skills commands; do
    [ -e "$DEST/$item" ] && left="$left $item"
  done
  if [ -n "$left" ]; then
    echo "  Note: left untouched (from a previous full install, still active):$left"
    echo "  The replaced opencode.jsonc no longer defines the agents/permissions they relied on."
  fi
  echo "✓ Installed (bare: models only)."
else
  echo "→ Installing the OpenCode Onyxia config globally into: $DEST"
  mkdir -p "$DEST/prompts" "$DEST/skills" "$DEST/commands"

  # Back up any existing config (config + AGENTS.md)
  if [ -f "$DEST/opencode.jsonc" ] || [ -f "$DEST/opencode.json" ] || [ -f "$DEST/AGENTS.md" ]; then
    ts="$(date +%Y%m%d-%H%M%S)"
    bak="$DEST/backup-$ts"
    echo "  Existing config detected → backing it up to $bak"
    mkdir -p "$bak"
    cp -f "$DEST"/opencode.json*  "$bak/" 2>/dev/null || true
    cp -f "$DEST"/AGENTS.md       "$bak/" 2>/dev/null || true
  fi

  # v1 used a singular command/ directory. v2 reads both, so a leftover copy
  # would shadow/duplicate the new commands: move it into the backup instead.
  if [ -d "$DEST/command" ]; then
    bak="${bak:-$DEST/backup-$(date +%Y%m%d-%H%M%S)}"
    mkdir -p "$bak"
    echo "  Legacy command/ directory found → moving it to $bak/command"
    mv "$DEST/command" "$bak/command"
  fi

  # Copy: config + context + prompts + skills + commands
  #  (GLOBAL skills live in ~/.config/opencode/skills/, without the .opencode prefix)
  cp -f  "$SRC/opencode.jsonc"        "$DEST/opencode.jsonc"
  cp -f  "$SRC/AGENTS.md"             "$DEST/AGENTS.md"
  cp -rf "$SRC/prompts/."             "$DEST/prompts/"
  cp -rf "$SRC/.opencode/skills/."    "$DEST/skills/"
  if [ -d "$SRC/.opencode/commands" ]; then
    cp -rf "$SRC/.opencode/commands/." "$DEST/commands/"
  fi

  # Bundled skill scripts must stay executable
  find "$DEST/skills" -type f \( -name "*.sh" -o -name "*.py" \) -path "*/scripts/*" \
    -exec chmod +x {} + 2>/dev/null || true

  # Optional: expose the same skills to Claude Code (~/.claude/skills)
  if [ "$WITH_CLAUDE" = true ]; then
    CLAUDE_SKILLS="$HOME/.claude/skills"
    echo "→ Also installing skills for Claude Code into: $CLAUDE_SKILLS"
    mkdir -p "$CLAUDE_SKILLS"
    cp -rf "$SRC/.opencode/skills/." "$CLAUDE_SKILLS/"
    find "$CLAUDE_SKILLS" -type f \( -name "*.sh" -o -name "*.py" \) -path "*/scripts/*" \
      -exec chmod +x {} + 2>/dev/null || true
    echo "  Tip: Claude Code reads project context from CLAUDE.md — consider copying"
    echo "  the relevant parts of AGENTS.md into ~/.claude/CLAUDE.md"
  fi

  echo "✓ Installed."
fi

echo
echo "Remaining steps (one time only):"
echo "  export OPENAI_BASE_URL=\"https://llm.lab.sspcloud.fr/api\""
echo "  export OPENAI_API_KEY=\"sk-……\"   # Open WebUI key"
echo "Then, from any project:  opencode  →  /models"
